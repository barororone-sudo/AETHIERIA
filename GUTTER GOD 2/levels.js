```javascript
// Classe pour les niveaux
class Levels {
  constructor() {
    this.niveauActuel = 1;
  }

  // Méthode pour initialiser les niveaux
  init() {
    // Initialisation du niveau actuel
    this.niveauActuel = 1;
  }

  // Méthode pour mettre à jour les niveaux
  update() {
    // Mise à jour du niveau actuel
    this.niveauActuel += 1;
  }
}

export default Levels;
```
